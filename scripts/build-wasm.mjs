import fs from 'node:fs';
import path from 'node:path';
import assert from 'node:assert/strict';
import {createRequire} from 'node:module';
import {execFileSync} from 'node:child_process';
const require=createRequire(import.meta.url),root=process.cwd(),cpp=path.join(root,'maiacpp');
const {Cpp98Compiler}=require('../maiacpp/compiler/cpp-compiler.js');
const {compileSource}=require('../maiacpp/maiac/compiler/c-compiler.js');
fs.mkdirSync('build',{recursive:true});
const emitted=path.join(root,'build/compiler.c');
const code=new Cpp98Compiler(path.join(root,'maia_glob_compile.cpp'),{astStrict:true,legacyFunctionHints:false}).compile();
assert.doesNotMatch(code,/stub-fallback|deterministic-fold/);
fs.writeFileSync(emitted,code);
execFileSync(process.env.CC||'clang',['--target=wasm32-unknown-unknown','-std=c89','-pedantic-errors','-ffreestanding','-Werror=implicit-function-declaration','-fsyntax-only',emitted],{stdio:'inherit'});
const linked=path.join(root,'build/linked.c');
fs.writeFileSync(linked,'#define MAIACPP_USE_C_ALLOCATOR\n'+[path.join(cpp,'maiac/src/stdlib.c'),path.join(cpp,'maiac/src/string.c'),path.join(cpp,'maiaregex/maia_regex.c'),path.join(root,'maia_glob.c'),emitted,path.join(root,'tests/driver.c')].map(p=>`#include "${p}"\n`).join(''));
const result=compileSource(fs.readFileSync(linked,'utf8'),{sourcePath:linked,resolveSystemIncludes:true,validate:true});
assert.ok(result.wasm,result.validationError?.message);
const bytes=Buffer.from(result.wasm),module=new WebAssembly.Module(bytes);
console.log(WebAssembly.Module.imports(module));
fs.writeFileSync('build/maiaglob-test.wasm',bytes);
console.log(`MaiaGlob generated C++98 frontend + C89 runtime -> MaiaCpp/MaiaC/WASM: ${bytes.length} bytes.`);
